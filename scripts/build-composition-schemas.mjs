// Generate the composition catalog and its JSON Schemas from the published metadata (ADR 0046 D3,
// data-composition.md §8): packages/components/src/composition/catalog.ts (what validateComposition
// and renderComposition accept) and packages/components/schemas/composition/ (one schema per element
// and the document schema). Run after build-metadata.mjs; `--check` fails when either is stale.
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as prettier from 'prettier';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pkg = join(root, 'packages/components');
const check = process.argv.includes('--check');
const BASE = 'https://oddkin.dev/schemas/composition';
const MODEL_BASE = 'https://oddkin.dev/schemas/components';
// Attributes whose value is followed as a URL: script URLs are refused like any model URL.
const URL_ATTRIBUTES = new Set(['href', 'src', 'formaction']);
// Record types a published model describes (packages/components/src/models), by CEM type name.
const MODEL_TYPES = { NavigationEntry: 'oddkin.navigation' };
// Native events an element's contract makes its activation, which the CEM does not list: odd-button
// stops `click` at the host while disabled or loading, so a click listener runs only on activation.
const NATIVE_EVENTS = { 'odd-button': ['click'] };

const json = async (file) => JSON.parse(await readFile(join(pkg, file), 'utf8'));
const metadata = await json('oddkin.metadata.json');
const cem = await json('custom-elements.json');
const declarations = new Map(
  cem.modules.flatMap((mod) => (mod.declarations ?? []).map((d) => [d.tagName, d])),
);

const STRING_LITERALS = /^"[^"]*"(?: \| "[^"]*")*$/;
const literals = (text) => [...text.matchAll(/"([^"]*)"/g)].map((match) => match[1]);
const bare = (text) => text.replace(/ \| undefined$/, '').trim();

/** The ValueType for a CEM type text, or undefined when JSON cannot carry it. */
function valueType(text, name) {
  const type = bare(text ?? '');
  if (type === 'string') return URL_ATTRIBUTES.has(name) ? 'url' : 'string';
  if (type === 'number') return 'number';
  if (type === 'boolean') return 'boolean';
  if (STRING_LITERALS.test(type)) return { enum: literals(type) };
  if (type === 'readonly string[]') return 'strings';
  const texts = /^Partial<\{((?: [\w]+: string;)+) \}>$/.exec(type);
  if (texts) return { texts: [...texts[1].matchAll(/(\w+): string;/g)].map((match) => match[1]) };
  const records = /^readonly (\w+)\[\]$/.exec(type);
  if (records && Object.hasOwn(MODEL_TYPES, records[1])) return { model: MODEL_TYPES[records[1]] };
  return undefined;
}

const catalog = {};
for (const tag of Object.values(metadata.components)
  .map((c) => c.tag)
  .sort()) {
  const d = declarations.get(tag);
  if (!d) throw new Error(`${tag}: no custom-elements.json declaration`);
  const attributes = {};
  for (const a of d.attributes ?? []) {
    const type = valueType(a.type?.text, a.name);
    if (!type)
      throw new Error(`${tag}: attribute "${a.name}" has an unsupported type ${a.type?.text}`);
    if (type === 'boolean' && a.default !== 'false')
      throw new Error(
        `${tag}: boolean attribute "${a.name}" defaults to ${a.default}; markup cannot turn it off`,
      );
    attributes[a.name] = type;
  }
  const properties = {};
  const fixed = [];
  for (const f of d.members ?? []) {
    if (f.kind !== 'field' || f.static || f.privacy || f.name.startsWith('_') || f.attribute)
      continue;
    const type = f.readonly ? undefined : valueType(f.type?.text, f.name);
    if (type) properties[f.name] = type;
    else fixed.push(f.name);
  }
  catalog[tag] = {
    attributes,
    properties,
    fixed: fixed.sort(),
    slots: (d.slots ?? []).map((s) => s.name).sort(),
    events: [...(d.events ?? []).map((e) => e.name), ...(NATIVE_EVENTS[tag] ?? [])].sort(),
  };
}

const format = (text, filepath) =>
  prettier
    .resolveConfig(filepath)
    .then((options) => prettier.format(text, { ...options, filepath }));

const catalogFile = join(pkg, 'src/composition/catalog.ts');
const catalogText = await format(
  `// Generated by scripts/build-composition-schemas.mjs from the published metadata: do not edit.
// What a composition may write on each element (data-composition.md §8).
import type { Catalog } from './vocabulary.js';

export const CATALOG: Catalog = ${JSON.stringify(catalog)};
`,
  catalogFile,
);

let stale = 0;
const write = async (file, text) => {
  if (check) {
    const current = await readFile(file, 'utf8').catch(() => '');
    if (current !== text) {
      console.error(`stale: ${file.slice(root.length + 1).replace(/\\/g, '/')}`);
      stale++;
    }
  } else await writeFile(file, text);
};
// First: the schemas below need the compiled vocabulary, which compiles this catalog.
await write(catalogFile, catalogText);

/** JSON Schema for a value type, through the same @oddkin/core/model nodes validation uses. */
const vocabularyUrl = pathToFileURL(join(pkg, 'dist/composition/vocabulary.js')).href;
const { valueNode, NATIVE } = await import(vocabularyUrl);
const { defineModel } = await import(
  pathToFileURL(join(root, 'packages/core/dist/model/index.js')).href
);
const { toJSONSchema } = await import(
  pathToFileURL(join(root, 'packages/core/dist/model/schema.js')).href
);
function valueSchema(type) {
  if (typeof type === 'object' && 'model' in type) {
    const model = metadata.models[`model:${type.model}`];
    return { $ref: `${MODEL_BASE}/${type.model}.v${model.version}.json` };
  }
  const { $schema, $id, title, ...schema } = toJSONSchema(
    defineModel('oddkin.composition.value', { version: 1, schema: valueNode(type) }),
  );
  return schema;
}
const literal = (text) => {
  if (text === undefined || text === 'undefined') return undefined;
  try {
    return JSON.parse(text.replace(/^'(.*)'$/, (_, s) => JSON.stringify(s)));
  } catch {
    return undefined;
  }
};
const described = (schema, source) => {
  const out = { ...schema };
  if (source?.description) out.description = source.description;
  const value = literal(source?.default);
  if (value !== undefined) out.default = value;
  return out;
};
const object = (properties) => ({ type: 'object', additionalProperties: false, properties });
const ref = (name) => ({ $ref: `${BASE}/composition.v1.json#/$defs/${name}` });

const schemas = {};
for (const [tag, entry] of Object.entries(catalog)) {
  const d = declarations.get(tag);
  const attribute = (name) => (d.attributes ?? []).find((a) => a.name === name);
  const member = (name) => (d.members ?? []).find((m) => m.name === name);
  const properties = {
    element: { const: tag },
    id: ref('id'),
    slot: ref('slot'),
  };
  if (Object.keys(entry.attributes).length)
    properties.attributes = object(
      Object.fromEntries(
        Object.entries(entry.attributes).map(([name, type]) => [
          name,
          described(valueSchema(type), attribute(name)),
        ]),
      ),
    );
  if (Object.keys(entry.properties).length)
    properties.properties = object(
      Object.fromEntries(
        Object.entries(entry.properties).map(([name, type]) => [
          name,
          described(valueSchema(type), member(name)),
        ]),
      ),
    );
  if (entry.slots.length) properties.children = { type: 'array', items: ref('node') };
  if (entry.events.length)
    properties.actions = object(Object.fromEntries(entry.events.map((e) => [e, ref('action')])));
  schemas[`${tag}.v1.json`] = {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: `${BASE}/${tag}.v1.json`,
    title: tag,
    description: (d.description ?? '').split('\n\n')[0].replace(/\s*\n\s*/g, ' '),
    ...(entry.slots.length
      ? {
          $comment: `Slots: ${entry.slots.map((s) => (s ? `"${s}"` : 'default')).join(', ')}. A child names a slot with "slot"; text and children without "slot" go to the default slot.`,
        }
      : {}),
    type: 'object',
    additionalProperties: false,
    required: ['element'],
    properties,
  };
}

const natives = Object.fromEntries(
  Object.entries(NATIVE).map(([tag, entry]) => [
    `native-${tag}`,
    {
      type: 'object',
      additionalProperties: false,
      required: ['element'],
      properties: {
        element: { const: tag },
        id: ref('id'),
        slot: ref('slot'),
        ...(Object.keys(entry.attributes).length
          ? {
              attributes: object(
                Object.fromEntries(
                  Object.entries(entry.attributes).map(([name, type]) => [name, valueSchema(type)]),
                ),
              ),
            }
          : {}),
        children: { type: 'array', items: ref('node') },
      },
    },
  ]),
);
schemas['composition.v1.json'] = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $id: `${BASE}/composition.v1.json`,
  title: 'Oddkin composition',
  description:
    'An interface described as data: published Oddkin elements and native text elements, their attributes and properties, text, and events mapped to action names. Rendered by renderComposition() from @oddkin/components/composition.',
  $comment:
    'Also enforced by validateComposition(), not expressible here: a slot must be published by the parent; text only where the parent has a default slot; list items only in lists; unique ids; model rules; at most 16 levels and 500 nodes by default.',
  type: 'object',
  additionalProperties: false,
  required: ['version', 'root'],
  properties: {
    $schema: { type: 'string' },
    version: { const: 1 },
    root: { type: 'array', items: { $ref: '#/$defs/node' } },
  },
  $defs: {
    node: {
      oneOf: [
        { type: 'string', description: 'Text, rendered as a text node.' },
        ...Object.keys(natives).map((name) => ({ $ref: `#/$defs/${name}` })),
        ...Object.keys(catalog).map((tag) => ({ $ref: `${tag}.v1.json` })),
      ],
    },
    id: {
      type: 'string',
      pattern: '^[A-Za-z][\\w-]*$',
      description: "The element's id, unique in the document.",
    },
    slot: { type: 'string', minLength: 1, description: 'A named slot of the parent element.' },
    action: {
      type: 'string',
      pattern: '^[a-z][a-zA-Z0-9-]*(?:\\.[a-zA-Z0-9-]+)*$',
      description: 'An action name the host handles, such as "settings.save"; never code.',
    },
    ...natives,
  },
};

const out = join(pkg, 'schemas/composition');
await mkdir(out, { recursive: true });
for (const [file, schema] of Object.entries(schemas))
  await write(join(out, file), `${JSON.stringify(schema, null, 2)}\n`);
for (const file of await readdir(out))
  if (!Object.hasOwn(schemas, file)) {
    if (check) {
      console.error(`stale: packages/components/schemas/composition/${file}`);
      stale++;
    } else await rm(join(out, file));
  }
if (stale) {
  console.error('Run node scripts/build-composition-schemas.mjs after npm run build.');
  process.exit(1);
}
console.log(
  `Composition ${check ? 'checked' : 'written'}: ${Object.keys(catalog).length} elements, ${Object.keys(schemas).length} schemas`,
);
