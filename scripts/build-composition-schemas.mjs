// Generate @oddkin/components' composition catalog and its JSON Schemas from its published manifest
// (ADR 0046 D3, data-composition.md §8), with the generator every library uses
// (@oddkin/analyzer's compositionCatalog and compositionSchemas): packages/components/src/composition/
// catalog.ts (what validateComposition and renderComposition accept by default) and
// packages/components/schemas/composition/ (one schema per element and the document schema).
// Run after build-metadata.mjs; `--check` fails when either is stale.
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as prettier from 'prettier';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pkg = join(root, 'packages/components');
const check = process.argv.includes('--check');
const { compositionCatalog, compositionSchemas } = await import(
  pathToFileURL(join(root, 'packages/analyzer/dist/composition.js')).href
);

const json = async (file) => JSON.parse(await readFile(join(pkg, file), 'utf8'));
const metadata = await json('oddkin.metadata.json');
const cem = await json('custom-elements.json');

const { catalog, diagnostics } = compositionCatalog(cem, {
  // Record types a published model describes (packages/components/src/models), by CEM type name.
  modelTypes: { NavigationEntry: 'oddkin.navigation' },
  // Native events an element's contract makes its activation, which the CEM does not list:
  // odd-button stops `click` at the host while disabled or loading, so a listener runs only on
  // activation.
  events: { 'odd-button': ['click'] },
});
// Every published attribute of Oddkin's own elements must be writable.
if (diagnostics.length) throw new Error(diagnostics.map((d) => d.message).join('\n'));
const tags = Object.values(metadata.components)
  .map((c) => c.tag)
  .sort();
if (JSON.stringify(tags) !== JSON.stringify(Object.keys(catalog)))
  throw new Error('The manifest and the metadata name different elements.');

const format = (text, filepath) =>
  prettier
    .resolveConfig(filepath)
    .then((options) => prettier.format(text, { ...options, filepath }));

const catalogFile = join(pkg, 'src/composition/catalog.ts');
const catalogText = await format(
  `// Generated by scripts/build-composition-schemas.mjs from the published metadata: do not edit.
// What a composition may write on each element (data-composition.md §8).
import type { Catalog } from './vocabulary.js';

export const CATALOG: Catalog = ${JSON.stringify(catalog)};
`,
  catalogFile,
);

let stale = 0;
const write = async (file, text) => {
  if (check) {
    const current = await readFile(file, 'utf8').catch(() => '');
    if (current !== text) {
      console.error(`stale: ${file.slice(root.length + 1).replace(/\\/g, '/')}`);
      stale++;
    }
  } else await writeFile(file, text);
};
await write(catalogFile, catalogText);

// A model-typed value refers to the model's published schema.
const modelSchemas = Object.fromEntries(
  Object.values(metadata.models ?? {}).map((model) => [
    model.name,
    `https://oddkin.dev/schemas/components/${model.name}.v${model.version}.json`,
  ]),
);
const schemas = compositionSchemas(catalog, cem, {
  base: 'https://oddkin.dev/schemas/composition/',
  modelSchemas,
  title: 'Oddkin composition',
  description:
    'An interface described as data: published Oddkin elements and native text elements, their attributes and properties, text, and events mapped to action names. Rendered by renderComposition() from @oddkin/components/composition.',
});

const out = join(pkg, 'schemas/composition');
await mkdir(out, { recursive: true });
for (const [file, schema] of Object.entries(schemas))
  await write(join(out, file), `${JSON.stringify(schema, null, 2)}\n`);
for (const file of await readdir(out))
  if (!Object.hasOwn(schemas, file)) {
    if (check) {
      console.error(`stale: packages/components/schemas/composition/${file}`);
      stale++;
    } else await rm(join(out, file));
  }
if (stale) {
  console.error('Run node scripts/build-composition-schemas.mjs after npm run build.');
  process.exit(1);
}
console.log(
  `Composition ${check ? 'checked' : 'written'}: ${Object.keys(catalog).length} elements, ${Object.keys(schemas).length} schemas`,
);
