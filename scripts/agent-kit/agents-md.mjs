/**
 * Agent-kit pilot, the repository's AGENTS.md section (IMPLEMENTATION_PLAN.md M5 item 862;
 * agent-tooling.md §5): setup, component conventions, and verification commands, generated from
 * the workspace's manifests and published metadata and written between managed markers. Text
 * outside the markers is never changed; every update is shown as a diff first.
 *
 *   node scripts/agent-kit/agents-md.mjs [--root <dir>] [--write | --check]
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { resolveProjectContext } from './context.mjs';

export const BEGIN =
  '<!-- oddkin:agents:begin (generated by node scripts/agent-kit/agents-md.mjs --write; edit outside these markers) -->';
export const END = '<!-- oddkin:agents:end -->';

const LAYOUTS = {
  folders:
    'one folder per component: the class, `<name>.template.ts`, `<name>.styles.ts`, `<name>.definition.ts` (`compose()`), `<name>.define.ts` (the only module that registers), a side-effect-free `index.ts`, and development-only `<name>.examples.ts` (IMPLEMENTATION_PLAN.md §3.3)',
  colocated: 'class, template, and styles in one module (colocated authoring)',
  mixed:
    'both component folders and colocated modules are in use; follow the neighbouring components',
  unknown: 'no components were found in the published metadata',
};

/** The managed section for a workspace, markers included. */
export function renderSection(project) {
  const { context } = project;
  const root = JSON.parse(readFileSync(join(project.root, 'package.json'), 'utf8'));
  const owned = project.libraries.filter((l) => l.owned);
  const devDependencies = { ...root.dependencies, ...root.devDependencies };
  const metadataPath = (name) => context.packages.find((p) => p.name === name)?.metadata;
  const lines = [
    BEGIN,
    '',
    '## Working in this repository',
    '',
    `- Setup: Node ${root.engines?.node ?? '(no engines field)'}, then \`npm install\`${devDependencies['@playwright/test'] ? '; `npx playwright install chromium firefox webkit` for browser tests' : ''}.`,
    `- Workspace packages: ${project.workspace.map((p) => `\`${p.name}\` (${p.dir})`).join(', ')}.`,
    `- Component layout (detected from published metadata): ${LAYOUTS[context.conventions.componentLayout]}.`,
    ...(owned.length
      ? [
          `- Component metadata is generated by the build into ${owned.map((l) => `\`${metadataPath(l.name)}\``).join(', ')}; never edit it by hand.`,
        ]
      : []),
    '- Commands:',
    ...Object.entries(context.commands).map(([key, command]) => `  - ${key}: \`${command}\``),
    `- Agent kits: each component package ships one matched to its version (${owned.map((l) => `\`node_modules/${l.name}/agent/GUIDE.md\``).join(', ')}; written by the build with \`node scripts/agent-kit/package-kits.mjs\`, \`--check\` to find stale ones). In this repository, \`node scripts/agent-kit/kit.mjs\` writes them into \`.oddkin/agent-kit/\`; add \`--check\` to find stale kits.`,
    '- Order of work, scope, status, and evidence: `IMPLEMENTATION_PLAN.md` (the priority plan first, then the milestones and §11 continuation), `docs/progress-log.md` (one row per slice), and `docs/verification.md` (record only observed results).',
    '',
    END,
  ];
  return lines.join('\n');
}

/** `text` with its managed section replaced, or the section appended when there is none. */
export function updateAgentsMd(text, section) {
  const begin = text.indexOf(BEGIN.slice(0, BEGIN.indexOf(' (')));
  const end = text.indexOf(END);
  if (begin === -1 && end === -1)
    return text.trim() ? `${text.replace(/\s*$/, '')}\n\n${section}\n` : `${section}\n`;
  if (begin === -1 || end === -1 || end < begin)
    throw new Error('AGENTS.md has one managed marker without the other; fix the markers by hand.');
  return `${text.slice(0, begin)}${section}${text.slice(end + END.length)}`;
}

/** Lines removed (`-`) and added (`+`) between two texts, in order; unchanged lines omitted. */
export function lineDiff(before, after) {
  const a = before.split('\n');
  const b = after.split('\n');
  const removed = a.filter((line) => !b.includes(line)).map((line) => `- ${line}`);
  const added = b.filter((line) => !a.includes(line)).map((line) => `+ ${line}`);
  return [...removed, ...added];
}

export async function main(argv = process.argv.slice(2)) {
  const usage = 'Usage: node scripts/agent-kit/agents-md.mjs [--root <dir>] [--write | --check]';
  let values;
  try {
    ({ values } = parseArgs({
      args: argv,
      options: {
        root: { type: 'string', default: '.' },
        write: { type: 'boolean', default: false },
        check: { type: 'boolean', default: false },
        help: { type: 'boolean', short: 'h', default: false },
      },
    }));
  } catch (error) {
    console.error(`${error.message}\n${usage}`);
    return 2;
  }
  if (values.help || (values.write && values.check)) {
    console.log(usage);
    return values.help ? 0 : 2;
  }
  const file = join(resolve(values.root), 'AGENTS.md');
  const before = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const after = updateAgentsMd(before, renderSection(resolveProjectContext(values.root)));
  if (after === before) {
    console.log('AGENTS.md: managed section current.');
    return 0;
  }
  const diff = lineDiff(before, after);
  console.log(`AGENTS.md${before ? '' : ' (new file)'}:\n${diff.join('\n')}`);
  if (values.check) {
    console.error('error agent.agentsMd.stale: run node scripts/agent-kit/agents-md.mjs --write');
    return 1;
  }
  if (values.write) {
    writeFileSync(file, after);
    console.log('AGENTS.md written.');
  } else console.log('Dry run: add --write to apply.');
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  process.exitCode = await main();
