const p = (...xy) =>
  `M ${xy.slice(0, 2).join(' ')} ${xy.slice(2).reduce((s, v, i) => s + (i % 2 === 0 ? ' L ' : ' ') + v, '')}`;
const poly = (...xy) => p(...xy) + ' Z';
const c = (x, y, r) => `M ${x - r} ${y} a ${r} ${r} 0 1 0 ${r * 2} 0 a ${r} ${r} 0 1 0 ${-r * 2} 0`;
const r = (x, y, w, h, a = 1) =>
  `M ${x + a} ${y} H ${x + w - a} Q ${x + w} ${y} ${x + w} ${y + a} V ${y + h - a} Q ${x + w} ${y + h} ${x + w - a} ${y + h} H ${x + a} Q ${x} ${y + h} ${x} ${y + h - a} V ${y + a} Q ${x} ${y} ${x + a} ${y} Z`;
const plus = (x, y, a = 2) => p(x - a, y, x + a, y) + p(x, y - a, x, y + a);
const cross = (x, y, a = 1.6) => p(x - a, y - a, x + a, y + a) + p(x + a, y - a, x - a, y + a);
const tick = (x, y, a = 2) => p(x - a, y, x - 0.4, y + 1.5, x + a, y - 1.5);
const pin = 'M 10 18 S 4 12.4 4 8 A 6 6 0 0 1 16 8 C 16 12.4 10 18 10 18 Z';
const heart = 'M 10 17 L 3.4 10.6 C -1 5.8 5.5 .8 10 5 C 14.5 .8 21 5.8 16.6 10.6 Z';
const head = (x = 10, y = 5, rad = 2.5) => c(x, y, rad);
const person = head() + 'M 4 17 V 14 C 4 9 16 9 16 14 V 17';
const magnify = c(8, 8, 5) + p(12, 12, 17, 17);
const items = [];
function group(domain, category, entries) {
  for (const [name, label, ...parts] of entries)
    items.push({ domain, category, name, label, path: parts.join(' ') });
}

