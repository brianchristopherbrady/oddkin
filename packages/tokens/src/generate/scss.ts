/**
 * Sass outputs (theming-and-styling.md §6, §11.5): a references module (`$tokens`, `token()`,
 * `$conditions`, `when()`) and a literal values module (`$values`, `value()`), from the same
 * resolved theme as the CSS and TypeScript outputs. Pure and deterministic, like them.
 */
import { cssVariable } from './graph.js';
import type { ResolvedTheme } from './resolve.js';
import { literal } from './ts.js';

const header = (theme: ResolvedTheme, what: string, usage: string) =>
  `// ${what} for theme "${theme.name}". Generated by @oddkin/tokens: change the theme configuration instead of editing this file.\n// ${usage}\n`;

/**
 * A literal as a Sass value. A comma list (a font stack, layered shadows) must be parenthesized so a
 * map keeps it whole; parentheses around any other value change nothing, so every value with a
 * comma gets them.
 */
const sassValue = (text: string) => (text.includes(',') ? `(${text})` : text);
const quoted = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/**
 * The references module: `token('space.md')` is `var(--odd-space-md)`, which follows runtime theme,
 * mode, product, and density scopes, and `@include when('navigation.expanded') { … }` wraps its
 * content in the condition's literal query.
 */
export function emitScssRefs(theme: ResolvedTheme): string {
  const tokens = [...theme.tokens.keys()]
    .map((name) => `  ${quoted(name)}: ${quoted(cssVariable(name))},`)
    .join('\n');
  const conditions = [...theme.conditions.values()]
    .map((c) => `  ${quoted(c.name)}: (kind: ${quoted(c.kind)}, query: ${quoted(c.query)}),`)
    .join('\n');
  return `${header(theme, 'Token references', `@use '<path>/${theme.name}.refs' as oddkin; then oddkin.token('space.md') is var(--odd-space-md).`)}@use 'sass:map';
@use 'sass:string';

/// Every token of the theme, by name, with its custom property.
$tokens: (
${tokens}
);

/// Named conditions: a container or media query each, with its literal prelude.
$conditions: (
${conditions}
);

/// A \`var()\` reference to a token, with an optional fallback; unknown names are errors.
@function token($name, $fallback: null) {
  @if not map.has-key($tokens, $name) {
    @error 'No token named "#{$name}" in theme "${theme.name}".';
  }
  $property: map.get($tokens, $name);
  @if $fallback == null {
    @return string.unquote('var(#{$property})');
  }
  @return string.unquote('var(#{$property}, #{$fallback})');
}

/// Wraps its content in the named condition's container or media query.
@mixin when($name) {
  @if not map.has-key($conditions, $name) {
    @error 'No condition named "#{$name}" in theme "${theme.name}".';
  }
  $condition: map.get($conditions, $name);
  @if map.get($condition, 'kind') == 'container' {
    @container #{map.get($condition, 'query')} {
      @content;
    }
  } @else {
    @media #{map.get($condition, 'query')} {
      @content;
    }
  }
}
`;
}

/**
 * The literal values module: `value('space.md')` is the base theme's value, compiled in; it does not
 * follow runtime themes. A value that differs by mode needs `$mode: light` or `$mode: dark`.
 */
export function emitScssValues(theme: ResolvedTheme): string {
  const values = [...theme.tokens.keys()]
    .map((name) => {
      const value = literal(theme, name);
      return `  ${quoted(name)}: ${
        typeof value === 'string'
          ? sassValue(value)
          : `(light: ${sassValue(value.light)}, dark: ${sassValue(value.dark)})`
      },`;
    })
    .join('\n');
  return `${header(theme, 'Literal token values', `@use '<path>/${theme.name}.values' as values; then values.value('space.md') is the base theme's value.`)}@use 'sass:map';
@use 'sass:meta';

/// Every token's literal value in the base theme (no product, density, or profile applied);
/// a value that differs by mode is a map of light and dark.
$values: (
${values}
);

/// A token's literal value, compiled in; pass $mode for a value that differs by mode.
@function value($name, $mode: null) {
  @if not map.has-key($values, $name) {
    @error 'No token named "#{$name}" in theme "${theme.name}".';
  }
  $value: map.get($values, $name);
  @if meta.type-of($value) != 'map' {
    @return $value;
  }
  @if $mode == null {
    @error '"#{$name}" differs by mode in theme "${theme.name}": pass $mode: light or $mode: dark.';
  }
  @if not map.has-key($value, $mode) {
    @error 'No mode "#{$mode}" in theme "${theme.name}": use light or dark.';
  }
  @return map.get($value, $mode);
}
`;
}
