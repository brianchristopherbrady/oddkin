/**
 * TypeScript and JSON outputs: typed references (`TokenName`, `token()`), literal
 * values, and inspection metadata. Pure and deterministic, like the CSS emitter.
 * Contract: theming-and-styling.md §6.
 */
import type { Mode } from '../theme/types.js';
import type { Diagnostic } from './diagnostics.js';
import {
  compareNames,
  compileValue,
  cssVariable,
  dependents,
  isModeDependent,
  resolveLiteral,
} from './graph.js';
import type { ResolvedTheme } from './resolve.js';

const header = (theme: ResolvedTheme, what: string) =>
  `// ${what} for theme "${theme.name}". Generated by @mote/tokens: change the theme configuration instead of editing this file.\n`;

/** `export type TokenName = 'a' | 'b' | …;` */
export function emitTokenNameType(theme: ResolvedTheme): string {
  const names = [...theme.tokens.keys()].map((n) => `  | '${n}'`).join('\n');
  return `${header(theme, 'Token names')}export type TokenName =\n${names};\n`;
}

/** A standalone module with `TokenName` and `token()` for a configured theme. */
export function emitRefsModule(theme: ResolvedTheme): string {
  return `${emitTokenNameType(theme)}
/** \`var(--mote-…)\` reference that follows runtime theme, mode, product, and density scopes. */
export function token(name: TokenName, fallback?: string): string {
  return \`var(--mote-\${name.replace(/\\./g, '-')}\${fallback === undefined ? '' : \`, \${fallback}\`})\`;
}
`;
}

type Literal = string | { readonly light: string; readonly dark: string };
interface Tree {
  [key: string]: Tree | Literal;
}

function literal(theme: ResolvedTheme, name: string): Literal {
  const token = theme.tokens.get(name);
  const resolve = (mode: Mode) => resolveLiteral(theme.tokens, name, mode) ?? '';
  if (token && isModeDependent(token.value, theme.modes))
    return { light: resolve('light'), dark: resolve('dark') };
  return resolve(theme.modes[0] ?? 'light');
}

const isLeaf = (value: Tree | Literal): value is Literal =>
  typeof value === 'string' || 'light' in value;

/** Nested literal values of the base theme (no product or density scope applied). */
export function valuesTree(theme: ResolvedTheme): Tree {
  const root: Tree = {};
  for (const name of theme.tokens.keys()) {
    const segments = name.split('.');
    let node = root;
    segments.forEach((segment, i) => {
      const existing = node[segment];
      if (i === segments.length - 1) {
        if (existing !== undefined)
          throw new Error(`Token "${name}" is both a value and a group in values output.`);
        node[segment] = literal(theme, name);
        return;
      }
      if (existing !== undefined && isLeaf(existing))
        throw new Error(
          `Token "${name}" nests under the value "${segments.slice(0, i + 1).join('.')}".`,
        );
      node = (node[segment] ??= {}) as Tree;
    });
  }
  return root;
}

function serialize(value: Tree | Literal, indent: string): string {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const entries = Object.entries(value);
  const inner = `${indent}  `;
  const body = entries
    .map(
      ([key, v]) =>
        `${inner}${/^[A-Za-z_$][\w$]*$/.test(key) ? key : `'${key}'`}: ${serialize(v as Tree | Literal, inner)},`,
    )
    .join('\n');
  return `{\n${body}\n${indent}}`;
}

/**
 * `values` literal module. Mode-dependent tokens are `{ light, dark }`. Literals are
 * compiled in and do not follow runtime themes; use `token()` for styling.
 */
export function emitValuesModule(theme: ResolvedTheme): string {
  return `${header(theme, 'Literal token values')}export const values = ${serialize(valuesTree(theme), '')} as const;\n`;
}

/** Inspection metadata: definitions, provenance, literals, scopes, and diagnostics. */
export function emitInspectJson(
  theme: ResolvedTheme,
  diagnostics: readonly Diagnostic[] = [],
): string {
  const modeClosure =
    theme.modes.length > 1 ? [...dependents(theme.tokens, new Set(['$mode']), theme.modes)] : [];
  const data = {
    theme: theme.name,
    modes: theme.modes,
    tokens: [...theme.tokens.values()].map((t) => ({
      name: t.name,
      cssVariable: cssVariable(t.name),
      category: t.category,
      type: t.type,
      origin: t.origin,
      definition: t.value,
      css: compileValue(t.value, theme.modes),
      value: literal(theme, t.name),
      ...(t.provenance ? { provenance: t.provenance } : {}),
      ...(t.density ? { density: true } : {}),
      ...(t.minimum ? { minimum: t.minimum } : {}),
      ...(t.description ? { description: t.description } : {}),
    })),
    scopes: [
      ...(modeClosure.length
        ? [
            {
              selector: '[data-mote-mode]',
              changed: ['$mode'],
              redeclared: modeClosure.sort(compareNames),
            },
          ]
        : []),
      ...theme.scopes.map((s) => ({
        selector: `[data-mote-${s.kind}="${s.name}"]`,
        changed: s.changed,
        redeclared: [...s.tokens.keys()].filter((n) => !s.changed.includes(n)),
      })),
    ],
    diagnostics,
  };
  return `${JSON.stringify(data, null, 2)}\n`;
}
