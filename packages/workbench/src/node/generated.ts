/**
 * Generated directories (workbench.md §2.1). Workbench writes and deletes only inside a directory
 * that carries its marker file. It refuses an existing directory without one, rewrites only files
 * whose content changed, and removes files a run no longer produces. Symbolic links are removed
 * as links, never followed.
 */
import { existsSync } from 'node:fs';
import { lstat, mkdir, readdir, readFile, rm, rmdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

export const MARKER = 'oddkin-generated.json';
export const MARKER_CONTENT = `${JSON.stringify(
  {
    generator: '@oddkin/workbench',
    note: 'Generated by oddkin workbench. Every run replaces or removes the files in this directory; authored files never live here.',
  },
  null,
  2,
)}\n`;

export class GeneratedDirectoryError extends Error {
  constructor(
    readonly code: 'node.generated.unmarked' | 'node.generated.path',
    message: string,
  ) {
    super(message);
    this.name = 'GeneratedDirectoryError';
  }
}

/** Relative POSIX paths only: no empty, `.`, or `..` segments, drive letters, or backslashes. */
function checkPath(path: string): void {
  const segments = path.split('/');
  const bad = segments.some(
    (segment) => segment === '' || segment === '.' || segment === '..' || /[\\:\0]/.test(segment),
  );
  if (bad || path === MARKER)
    throw new GeneratedDirectoryError(
      'node.generated.path',
      `"${path}" is not a relative path inside the generated directory.`,
    );
}

async function writeIfChanged(file: string, content: string): Promise<boolean> {
  try {
    if ((await readFile(file, 'utf8')) === content) return false;
  } catch {
    // Missing: written below.
  }
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, content);
  return true;
}

/** Files under `dir` (links included, not followed) as POSIX paths, and directories bottom-up. */
async function walk(dir: string, prefix = ''): Promise<{ files: string[]; dirs: string[] }> {
  const files: string[] = [];
  const dirs: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory() && !entry.isSymbolicLink()) {
      const inner = await walk(join(dir, entry.name), rel);
      files.push(...inner.files);
      dirs.push(...inner.dirs, rel);
    } else files.push(rel);
  }
  return { files, dirs };
}

/**
 * Make `dir` hold exactly `files` (relative POSIX path → content) plus the marker. Returns the
 * paths written (new or changed) and removed.
 */
export async function writeGenerated(
  dir: string,
  files: ReadonlyMap<string, string>,
): Promise<{ written: string[]; removed: string[] }> {
  for (const path of files.keys()) checkPath(path);
  if (existsSync(dir)) {
    const stat = await lstat(dir);
    const entries = stat.isDirectory() && !stat.isSymbolicLink() ? await readdir(dir) : undefined;
    if (!entries || (entries.length > 0 && !entries.includes(MARKER)))
      throw new GeneratedDirectoryError(
        'node.generated.unmarked',
        `${dir} exists and was not generated by Workbench (it has no ${MARKER}), so it is left untouched. Remove it or choose another directory.`,
      );
  }
  await mkdir(dir, { recursive: true });
  await writeIfChanged(join(dir, MARKER), MARKER_CONTENT);
  const written: string[] = [];
  for (const [path, content] of files)
    if (await writeIfChanged(join(dir, ...path.split('/')), content)) written.push(path);
  const removed: string[] = [];
  const existing = await walk(dir);
  for (const path of existing.files) {
    if (path === MARKER || files.has(path)) continue;
    await rm(join(dir, ...path.split('/')), { force: true });
    removed.push(path);
  }
  for (const path of existing.dirs) {
    const full = join(dir, ...path.split('/'));
    if ((await readdir(full)).length === 0) await rmdir(full);
  }
  return { written, removed };
}
